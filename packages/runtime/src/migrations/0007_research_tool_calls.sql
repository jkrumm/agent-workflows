-- Every call a research agent made through the host's tool gate (host `workflows/research/gate.ts`), written as it
-- happens: the evidence a research run is scored and priced on (what it retrieved, what it saw, what each call cost)
-- survives a step retry and a host restart. Read, never consumed, by the run's `evidence` step.
create table {{schema}}.research_tool_calls (
  id bigint generated by default as identity primary key,
  run_id text not null,
  step_id text not null,
  tool text not null,
  -- sha256 of the canonical arguments: which call it was, without storing a question or a URL twice.
  args_digest text not null,
  ok boolean not null,
  -- URLs whose page text the call read, and URLs it only saw (search results).
  retrieved jsonb not null default '[]',
  seen jsonb not null default '[]',
  -- The runtime's `Usage` reports of the call (capability usage, an engine job's cost); `[]` for none.
  usage jsonb not null default '[]',
  -- `engine_research`: the engine's job id and its own reported cost (null: it reported none).
  engine_job text,
  engine_cost numeric,
  error text,
  created_at timestamptz not null default now()
);

create index research_tool_calls_step on {{schema}}.research_tool_calls (run_id, step_id, id);
-- A repeated question adopts the engine job it already started (same idempotency key): booked once per run.
create unique index research_tool_calls_engine_job on {{schema}}.research_tool_calls (run_id, engine_job)
  where engine_job is not null;
