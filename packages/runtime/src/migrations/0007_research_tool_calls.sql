-- Every call a research agent made through the host's tool gate (host `workflows/research/gate.ts`), written as it
-- happens: the evidence a research run is scored on (what it retrieved, what it only saw, whether the call worked,
-- which engine job it ran and what the engine said it cost) survives a step retry and a host restart. A call's cost is
-- booked on the run itself; an engine job's row is what keeps a job from being booked twice. Rows go with their run.
create table {{schema}}.research_tool_calls (
  id bigint generated by default as identity primary key,
  run_id text not null references {{schema}}.runs (id) on delete cascade,
  step_id text not null,
  tool text not null,
  -- sha256 of the canonical JSON of the arguments: which call it was, without storing a question or a URL twice.
  args_digest text not null,
  ok boolean not null,
  -- URLs whose page text the call read, and URLs it only saw (search results).
  retrieved jsonb not null default '[]',
  seen jsonb not null default '[]',
  -- `engine_research`: the engine's job id and the cost it reported for it when the job ended (null: unknown).
  engine_job text,
  engine_cost numeric,
  error text,
  created_at timestamptz not null default now()
);

create index research_tool_calls_step on {{schema}}.research_tool_calls (run_id, step_id, id);
