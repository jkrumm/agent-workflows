-- Per-agent learned facts (concept §7). A retrospective proposes, a human activates; only `active` facts are read
-- back into the agent's next run. `retire` is immediate; a retired fact stays on file so it is not proposed again.
create table {{schema}}.learnings (
  id integer generated by default as identity primary key,
  agent text not null,
  fact text not null,
  -- The run that proposed it (a retrospective run id), or 'manual'.
  source text not null,
  -- Run ids the proposing agent cited as evidence.
  evidence text[] not null default '{}',
  status text not null default 'proposed' check (status in ('proposed', 'active', 'retired')),
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  retired_at timestamptz,
  check ((status = 'retired') = (retired_at is not null))
);

-- The read-back path: the active facts of one agent, in the order they were activated.
create index learnings_active on {{schema}}.learnings (agent, activated_at, id) where status = 'active';
-- A fact is stored once per agent, retired rows included: a retired fact is a rejected one and is never proposed again
-- by a retrospective (a human can bring it back with `agw learnings add`).
create unique index learnings_fact on {{schema}}.learnings (agent, md5(fact));
