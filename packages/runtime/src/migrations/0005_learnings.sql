-- Per-agent learned facts (concept §7). A retrospective proposes, a human activates; only `active` facts are read
-- back into the agent's next run. `retire` is immediate and reversible by adding the fact again.
create table {{schema}}.learnings (
  id integer generated by default as identity primary key,
  agent text not null,
  fact text not null,
  -- The run that proposed it (a retrospective run id), or 'manual'.
  source text not null,
  -- Run ids the proposing agent cited as evidence.
  evidence text[] not null default '{}',
  status text not null default 'proposed' check (status in ('proposed', 'active', 'retired')),
  created_at timestamptz not null default now(),
  activated_at timestamptz,
  retired_at timestamptz,
  check ((status = 'retired') = (retired_at is not null))
);

-- The read-back path: the active facts of one agent.
create index learnings_active on {{schema}}.learnings (agent, id) where status = 'active';
-- The same fact for the same agent is stored once while it is live; a retired fact may be proposed again.
create unique index learnings_live_fact on {{schema}}.learnings (agent, md5(fact)) where status <> 'retired';
